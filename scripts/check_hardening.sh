#!/bin/sh
# Проверка того, что меры защиты РЕАЛЬНО применены к этому контейнеру.
#
# Запускается ИЗНУТРИ работающего контейнера:
#
#     docker exec <контейнер> sh scripts/check_hardening.sh
#
# Код возврата: 0 — все меры на месте, 1 — хотя бы одна отсутствует.
#
# ★ЗАЧЕМ ЭТО ОТДЕЛЬНЫМ СКРИПТОМ, А НЕ СПИСКОМ КОМАНД В ОТЧЁТЕ.
#
# Меры защиты задаются флагами запуска, то есть действуют ровно настолько,
# насколько развёртывающий их не забыл. Список команд в документе проверяет
# только того, кто открыл документ. Скрипт едет вместе с образом и отвечает
# одним словом.
#
# ★КАЖДАЯ ПРОВЕРКА ОБЯЗАНА РАЗЛИЧАТЬ РЕЖИМЫ, И ЭТО НЕ ОЧЕВИДНОСТЬ.
# 26.08.2026 выяснилось, что две из трёх напечатанных тогда проверок отвечают
# одинаково с флагами и без них: и пустой набор эффективных возможностей
# (`CapEff`), и отказ записи в системный каталог даёт сам непривилегированный
# пользователь. Рецензент, забывший флаги, видел бы зелёные строки.
#
# Поэтому здесь: ограничивающий набор `CapBnd`, а не эффективный; запись туда,
# куда пользователь писать ВПРАВЕ (`/app`), а не в системный каталог; тип
# файловой системы на `/tmp`, а не просто возможность записи в него.
#
# ★ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ. Идентификатор пользователя (`id -u` = 1000) не
# проверяется: `USER analyst` задан в образе, и ответ одинаков при любых флагах
# запуска. Это мера поставки, а не запуска, и включать её сюда значило бы
# добавить строку, которая зелена всегда. Публикация порта только на петлевой
# интерфейс изнутри контейнера не видна вовсе — она проверяется на ХОСТЕ:
#     ss -ltn | grep 8501     # ожидается 127.0.0.1:8501, а не 0.0.0.0:8501

failures=0

report() {
    # $1 — мера, $2 — вердикт (ok/fail), $3 — что увидели
    if [ "$2" = "ok" ]; then
        printf '  ✔ %-42s %s\n' "$1" "$3"
    else
        printf '  ✘ %-42s %s\n' "$1" "$3"
        failures=$((failures + 1))
    fi
}

echo "Меры защиты, применённые к этому контейнеру:"

# 1. Неизменяемая корневая ФС (--read-only).
#    Пробуем писать в /app — каталог, принадлежащий нашему пользователю.
#    Запись в /etc отказала бы и без флага, то есть ничего не различала бы.
probe=/app/.hardening-probe
if touch "$probe" 2>/dev/null; then
    rm -f "$probe"
    report "корневая ФС неизменяема (--read-only)" fail "запись в /app удалась"
else
    report "корневая ФС неизменяема (--read-only)" ok "запись в /app отклонена"
fi

# 2. Временный каталог в памяти (--tmpfs /tmp).
#    Без него при --read-only писать было бы некуда вовсе.
tmp_kind=$(stat -f -c %T /tmp 2>/dev/null || echo "неизвестно")
if [ "$tmp_kind" = "tmpfs" ]; then
    report "/tmp в памяти (--tmpfs /tmp)" ok "тип ФС: tmpfs"
else
    report "/tmp в памяти (--tmpfs /tmp)" fail "тип ФС: $tmp_kind"
fi

# 3. Снятые возможности ядра (--cap-drop=ALL).
#    ОГРАНИЧИВАЮЩИЙ набор, а не эффективный: эффективный пуст и без флага.
capbnd=$(awk '/^CapBnd:/ {print $2}' /proc/self/status 2>/dev/null)
if [ "$capbnd" = "0000000000000000" ]; then
    report "возможности ядра сняты (--cap-drop=ALL)" ok "CapBnd=$capbnd"
else
    report "возможности ядра сняты (--cap-drop=ALL)" fail "CapBnd=$capbnd"
fi

# 4. Запрет повышения привилегий (--security-opt no-new-privileges).
nnp=$(awk '/^NoNewPrivs:/ {print $2}' /proc/self/status 2>/dev/null)
if [ "$nnp" = "1" ]; then
    report "повышение привилегий запрещено" ok "NoNewPrivs=1"
else
    report "повышение привилегий запрещено" fail "NoNewPrivs=${nnp:-нет поля}"
fi

# 5. Потолок памяти (--memory).
mem=$(cat /sys/fs/cgroup/memory.max 2>/dev/null || echo "max")
if [ "$mem" != "max" ] && [ -n "$mem" ]; then
    report "потолок памяти задан (--memory)" ok "memory.max=$mem"
else
    report "потолок памяти задан (--memory)" fail "memory.max=$mem"
fi

# 6. Потолок процессорного времени (--cpus).
cpu=$(cat /sys/fs/cgroup/cpu.max 2>/dev/null || echo "max")
case "$cpu" in
    max*) report "потолок ЦП задан (--cpus)" fail "cpu.max=$cpu" ;;
    "")   report "потолок ЦП задан (--cpus)" fail "cpu.max не читается" ;;
    *)    report "потолок ЦП задан (--cpus)" ok "cpu.max=$cpu" ;;
esac

echo
if [ "$failures" -eq 0 ]; then
    echo "Все шесть мер на месте."
    exit 0
fi
echo "Мер не применено: $failures из 6."
echo "Штатный запуск со всеми мерами: docker compose up (см. compose.yaml)."
exit 1
