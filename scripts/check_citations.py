#!/usr/bin/env python
"""Проверка цитат: стоит ли названное число на названной странице.

★ЗАЧЕМ ЭТО ОТДЕЛЬНЫМ ИНСТРУМЕНТОМ. Проверяемость ссылок — предмет поставки, а
не свойство, которое можно объявить. Модель, которой дали правильный фрагмент,
всё равно способна приписать ему число из соседнего или округлить его «для
удобства»; ровно эту разновидность отказа продукт и обязан не допускать, и
объявлять её отсутствующей без проверки — то же самое, что не проверять.

★ПРОВЕРКА НЕ ДЕЛИТ МЕХАНИЗМ С ПРОВЕРЯЕМЫМ. Числа берутся не из того, что вернул
поиск, а заново из PDF-корпуса на диске — то есть из источника, а не из
посредника. Если бы сверка шла с выдачей поиска, она подтвердила бы согласие
модели с поиском и промолчала бы о том, что оба ошиблись вместе.

Выход: 0 — все числа найдены на названных страницах; 1 — есть непроверенные;
2 — проверка не отработала (нет корпуса, нет ответов). ★Второе не равно
первому: «не смогли проверить» обязано отличаться от «проверено и чисто».
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

# ★Шаблон ссылки берётся из библиотеки, а не пишется здесь второй раз. Копия
# разошлась бы с оригиналом при первой правке формата — и разошлась бы молча:
# сверка перестала бы находить цитаты и отчиталась бы о чистоте ровно тем же
# тоном, что и полная. Так уже случилось однажды, когда ссылки стали носить
# пометку о ступени чтения.
from neftegaz.tools.citations import CITATION  # noqa: E402

# Числа, которые вообще имеет смысл сверять: с десятичной частью. Целые вроде
# «2026» или «95%» — это годы и доли, они стоят в тексте ответа, а не в таблице,
# и требовать их дословного присутствия значило бы плодить ложные тревоги.
#
# ★ЗАПЯТАЯ РАВНОПРАВНА С ТОЧКОЙ. Отчёты английские и пишут «1.3», ответы русские
# и пишут «1,3». Первая редакция шаблона знала только точку, и все числа
# русского написания были для проверки НЕВИДИМЫ: сценарий 3 показал «сверено 0»
# при пятнадцати числах в ответе, и это выглядело как «нечего проверять», а не
# как слепота. Проверка, не видящая половину написаний, отчитывается о чистоте
# ровно тем же тоном, что и полная.
NUMBER = re.compile(r"\d+[.,]\d+")


def variants(number: str) -> tuple[str, ...]:
    """Написания одного и того же числа, которые надо искать в источнике."""
    return (number.replace(",", "."), number.replace(".", ","))


# Любая законная разметка источника. Расчёт и веб проверить по корпусу нельзя,
# но их НАЛИЧИЕ проверить можно и нужно: число без всякой ссылки — отдельный и
# худший отказ, чем число со ссылкой на не ту страницу.
ANY_MARK = re.compile(r"\[(Отчёт|Расчёт|Источник|Веб-источник)")

# Ответ агента внутри демо-файла. Ниже идут служебные разделы («Что происходило
# внутри», список фрагментов с косинусами) — там числа законно стоят без ссылок,
# и требовать их разметки значило бы плодить ложные тревоги.
ANSWER = re.compile(r"### Ответ агента\n(.*?)\n---\n", re.S)
QUESTION = re.compile(r"### Запрос\n(.*?)\n### ", re.S)


# Дословный вывод расчётного модуля, записанный в тот же файл. Числа прогноза
# в корпусе отчётов отсутствуют по природе — они посчитаны, а не процитированы,
# — но перенос числа ИЗ вывода инструмента В текст ответа проверить можно, и
# ★именно на этом шаге модель и ошибается: считает не она, а переписывает она.
# Проверяется перенос, не правильность расчёта; последнюю проверяют тесты
# расчётного модуля, и смешивать эти два утверждения нельзя.
TOOL_OUTPUT = re.compile(r"#### Выход расчётного модуля\s*```(.*?)```", re.S)


def answer_of(text: str) -> str:
    """Раздел с ответом, если файл — демо; иначе весь текст."""
    found = ANSWER.search(text)
    return found.group(1) if found else text


def tool_output_of(text: str) -> str:
    found = TOOL_OUTPUT.search(text)
    return normalise(found.group(1)) if found else ""


def question_of(text: str) -> str:
    """Вопрос пользователя, как он записан в демо-файле.

    ★Число, которым ответ ПОВТОРЯЕТ вопрос («прогноз при сокращении добычи на
    1.5 млн барр./сут»), не является утверждением о мире и источника не требует:
    его источник — спрашивающий, и он у читателя перед глазами. Это не поблажка
    проверке: утверждение, ДОБАВЛЯЮЩЕЕ число к вопросу, ссылку по-прежнему
    обязано нести.
    """
    found = QUESTION.search(text)
    return found.group(1) if found else ""


def blocks(text: str) -> list[str]:
    """Абзацы ответа: строки до пустой строки, склеенные в один кусок.

    ★СВЕРКА ИДЁТ БЛОКАМИ, А НЕ СТРОКАМИ, и это не украшение. Перечисление в
    ответе выглядит так: три строки с числами, и ссылка только на последней —
    она относится ко всему перечислению. Построчная сверка проверяла бы лишь
    последнюю строку, а остальные молча пропускала: замерено на демо, покрытие
    падало с 44 сверенных чисел до 19. Проверка, которая тихо сужает охват,
    опаснее отсутствующей — она печатает «не подтверждено: 0» ровно тем же
    тоном, что и полная.
    """
    result: list[str] = []
    current: list[str] = []
    for line in text.splitlines():
        if line.strip():
            current.append(line)
        elif current:
            result.append(" ".join(current))
            current = []
    if current:
        result.append(" ".join(current))
    return result


def segments(block: str) -> list[tuple[str, str | None]]:
    """Абзац, разрезанный по ссылкам: число принадлежит БЛИЖАЙШЕЙ СЛЕДУЮЩЕЙ.

    ★ЭТО ГЛАВНОЕ МЕСТО ВСЕЙ ПРОВЕРКИ. Итоговый абзац законно смешивает
    источники: предложение про EIA закрывается ссылкой на отчёт, следующее про
    ОПЕК — ссылкой на веб. Прежняя редакция брала абзац целиком и сверяла ВСЕ
    его числа со ВСЕМИ упомянутыми страницами отчётов — и объявила «0,6» и
    «54,8» неподтверждёнными, хотя они пришли из веба и на страницах отчёта
    стоять не обязаны. Продукт был прав, груб был инструмент.

    Ссылка закрывает то, что перед ней. Возвращается список (отрезок, вид
    ссылки); у хвоста после последней ссылки вид ``None`` — числа там не
    закрыты ничем.

    ★ССЫЛКИ, ИДУЩИЕ ПОДРЯД, — ОДНА ГРУППА. Фраза «в мае и июне прогноз составил
    109.73 и 109.78 соответственно [Отчёт …, май], [Отчёт …, июнь]» ставит оба
    числа ПЕРЕД первой ссылкой. Разрезав по ней, инструмент требовал бы найти
    оба числа на майской странице и объявлял бы июньское выдуманным — ложная
    тревога на живом ответе, поймана 31.08 на перегенерированном сценарии 4.
    Числа перед группой сверяются с объединением её страниц: различить, какое
    число к какой ссылке относится, по тексту нельзя в принципе, а требовать
    присутствия на ВСЕХ названных страницах — заведомо неверно.
    """
    result: list[tuple[str, str | None]] = []
    previous = 0
    for mark in ANY_MARK.finditer(block):
        closing = block.find("]", mark.start())
        end = closing + 1 if closing != -1 else mark.end()
        if end <= previous:
            continue  # вложенная скобка внутри уже разобранной ссылки
        # Приклеить смежные ссылки: между ними допустимы запятая, точка с
        # запятой, союз «и» и пробелы — всё, чем перечисление разделяют.
        # ★ТОЛЬКО ОДНОРОДНЫЕ. Склеив «[Отчёт …], [Источник …]», мы бы дали
        # ответу отмазку: число, не найденное на странице отчёта, списалось бы
        # на непроверяемый веб. Смешанная пара режется как прежде.
        while True:
            joined = re.match(r"[\s,;]*(?:и\s+)?", block[end:])
            after = end + joined.end() if joined else end
            following = ANY_MARK.match(block, after)
            if not following or following.group(1) != mark.group(1):
                break
            closing = block.find("]", following.start())
            if closing == -1:
                break
            end = closing + 1
        result.append((block[previous:end], mark.group(1)))
        previous = end
    tail = block[previous:]
    if tail.strip():
        result.append((tail, None))
    return result


def normalise(text: str) -> str:
    """Убрать то, что конвертер PDF расставляет произвольно."""
    return re.sub(r"[\s ]+", " ", text)


def load_corpus() -> dict:
    """Страницы всех отчётов: (дата, номер страницы) -> текст страницы."""
    from neftegaz.rag.ingest import parse_filename, read_pdf_pages

    pages: dict = {}
    for pdf in sorted((ROOT / "data" / "reports").glob("*.pdf")):
        meta = parse_filename(pdf.name)
        for page in read_pdf_pages(str(pdf)):
            pages[(meta.date, page["page"])] = normalise(page["text"])
    return pages


def run(answers: list[Path], pages: dict) -> tuple[int, dict]:
    """Сверить готовые ответы с готовым корпусом. Возвращает код и счётчики.

    ★ВЫНЕСЕНО ИЗ `main` РАДИ АВТОМАТИЧЕСКОЙ ПРИЁМКИ. Проверяемость ссылок —
    предмет поставки, а проверялась она запуском скрипта руками; пока проверка
    зависит от того, вспомнит ли о ней человек, её с тем же успехом может не
    быть. Тест вызывает `run` с подложными ответами и подложным корпусом и тем
    самым проверяет не только ответы, но и то, что проверка УМЕЕТ УПАСТЬ.

    Корпус приходит доводом, а не читается отсюда: настоящие отчёты в публичный
    репозиторий не выкладываются, и тест, который может работать только при них,
    в чужой копии молча превратился бы в пропуск.
    """
    checked = missing = unmarked = web = 0
    per_answer: list[tuple[str, int, int, int, int, set]] = []
    for answer in answers:
        # Счётчики этого ответа: итог по каждому сценарию отдельно нужен потому,
        # что общая сумма скрывает, ГДЕ именно нечего было проверять. Ответ, в
        # котором чисел нет вовсе, и ответ, все числа которого подтверждены, в
        # сумме выглядят одинаково, а это разные состояния.
        here_checked = here_missing = here_unmarked = here_web = 0
        sources: set = set()
        body = answer.read_text(encoding="utf-8")
        computed = tool_output_of(body)
        asked = question_of(body)
        for block in blocks(answer_of(body)):
            if "```" in block:
                continue  # дословный вывод инструмента, показанный как есть
            for segment, kind in segments(block):
                digits = NUMBER.findall(segment)
                if not digits:
                    continue
                for mark in ANY_MARK.finditer(segment):
                    sources.add(mark.group(1))

                # ★Хвост без ссылки. Абзац с числами и без всякой разметки
                # читается как собственное мнение системы; проверить его
                # читатель не может, а проверяемость и есть предмет поставки.
                if kind is None:
                    echoed = [d for d in digits if any(f in asked for f in variants(d))]
                    bare = [d for d in digits if d not in echoed]
                    if not bare:
                        continue  # ответ лишь повторил числа вопроса
                    unmarked += len(bare)
                    here_unmarked += len(bare)
                    # Подстановка вынесена из f-строки: обратный слэш внутри
                    # выражения f-строки разрешён только с Python 3.12, а образ
                    # закреплён на 3.11 (ТЗ требует 3.10+). Под 3.11 файл не
                    # разбирался вовсе, и сверка цитат в контейнере не работала.
                    shown = re.sub(r"[\\s ]+", " ", segment)[:70]
                    print(f"  ✗ {answer.name}: числа {bare} стоят без ссылки: «{shown}…»")
                    continue

                # ★Веб непроверяем ПО ПРИРОДЕ: страница живёт в сети и меняется.
                # Считать такие числа «сверенными» было бы неправдой, а считать
                # «непод­тверждёнными» — клеветой. Им нужен свой столбец.
                if kind in ("Источник", "Веб-источник"):
                    web += len(digits)
                    here_web += len(digits)
                    continue

                if kind == "Расчёт":
                    haystack, named = computed, "выводе расчётного модуля"
                else:
                    citations = list(CITATION.finditer(segment))
                    if not citations:
                        continue
                    haystack = ""
                    pieces = []
                    for citation in citations:
                        # Пятая группа — пометка о ступени чтения, дописанная в
                        # ссылку кодом. Для сверки чисел она безразлична: число
                        # либо стои́т на названной странице, либо нет, и спорность
                        # чтения этого не меняет.
                        _source, date, first, last, _note = citation.groups()
                        pieces.append(f"{date} с.{first}" + (f"-{last}" if last else ""))
                        for number in range(int(first), int(last or first) + 1):
                            haystack += " " + pages.get((date, number), "")
                    named = ", ".join(pieces)
                if not haystack.strip():
                    print(f"  ✗ {answer.name}: источник ({named}) недоступен для сверки")
                    missing += 1
                    here_missing += 1
                    continue
                for number in digits:
                    checked += 1
                    here_checked += 1
                    if not any(form in haystack for form in variants(number)):
                        missing += 1
                        here_missing += 1
                        print(f"  ✗ {answer.name}: {number} нет в {named}")
        per_answer.append(
            (answer.name, here_checked, here_missing, here_unmarked, here_web, sources)
        )

    print()
    print(
        f"{'сценарий':<44} {'сверено':>8} {'не подтв.':>10} {'без ссылки':>11} "
        f"{'веб':>5}  источники"
    )
    for name, done, bad, bare, from_web, sources in per_answer:
        # ★ТРИ СОСТОЯНИЯ, А НЕ ДВА. «Нечего проверять» обязано отличаться от
        # «проверено и чисто»: ответ без единого числа и ответ, все числа
        # которого подтверждены, в двузначной шкале выглядят одинаково, а это
        # разные вещи — во втором проверка работала, в первом ей не досталось
        # работы. Веб-источники непроверяемы по природе: их содержимое живёт в
        # сети и меняется, и объявить их сверенными было бы неправдой.
        if bad or bare:
            verdict = "✗ находка"
        elif done:
            verdict = "✓ чисто  "
        else:
            verdict = "· нечего "
        kinds = ", ".join(sorted(sources)) or "—"
        print(f"{verdict} {name[:34]:<34} {done:>8} {bad:>10} {bare:>11} {from_web:>5}  {kinds}")
    print(
        f"\nсверено чисел: {checked}, не подтверждено: {missing}, "
        f"без ссылки: {unmarked}, из веба (непроверяемо): {web}"
    )
    totals = {"checked": checked, "missing": missing, "unmarked": unmarked, "web": web}
    if missing or unmarked:
        return 1, totals
    # ★Ноль сверенных — не успех. Пустая проверка выдала бы «всё чисто» ровно
    # так же, как исправная, и это тот самый случай, когда проверка отвечает
    # одинаково при полном отказе проверяемого.
    if checked == 0:
        print(
            "проверка не отработала: в ответах не нашлось ни одного числа со ссылкой",
            file=sys.stderr,
        )
        return 2, totals
    return 0, totals


def main() -> int:
    # Каталог ответов задаётся первым доводом: это позволяет проверить саму
    # проверку на подложных ответах, не трогая настоящие.
    where = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "demo"
    answers = sorted(where.glob("*.md"))
    if not answers:
        print(f"проверка не отработала: в {where} нет ответов", file=sys.stderr)
        return 2
    pages = load_corpus()
    if not pages:
        print("проверка не отработала: корпус в data/reports пуст", file=sys.stderr)
        return 2
    print(f"корпус: {len(pages)} страниц, ответов: {len(answers)}")
    code, _totals = run(answers, pages)
    return code


if __name__ == "__main__":
    raise SystemExit(main())
