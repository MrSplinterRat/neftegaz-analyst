"""Вход в интерфейс: тот же Streamlit, но запускаем его МЫ, а не его CLI.

★Зачем нужен собственный вход, если есть штатное `streamlit run ui/app.py`.

Продукт обещает локальность: корпус отчётов, индекс и переписка не покидают
машину заказчика. Streamlit этому обещанию не подчиняется по умолчанию и делает
две вещи, которых мы не заказывали.

1. **Обращение к постороннему серверу на каждом безголовом старте.** Чтобы
   напечатать строку «External URL: <внешний адрес>», Streamlit выполняет
   блокирующий HTTP-запрос к `http://checkip.amazonaws.com` — сначала по
   открытому HTTP, при неудаче по HTTPS (`streamlit/net_util.py`, вызов из
   `streamlit/web/bootstrap.py`). Запрос происходит при `server.headless = true`,
   то есть ровно в том режиме, в котором работает наш контейнер. Настройкой
   `browser.gatherUsageStats = false` он НЕ отключается: это разные механизмы.
   Наружу при этом уходит сам факт запуска с адреса заказчика, а в консоль
   печатается его внешний IP — в системе, которую мы продаём как замкнутую,
   это выглядит хуже, чем стоит.

2. **Объявление о сборе статистики.** При запуске без нашего `.streamlit/config.toml`
   Streamlit печатает «Collecting usage statistics…» и заводит идентификатор
   машины. Наш конфиг это выключает, но конфиг — файл в каталоге, и он
   действует только если запуск случился из этого каталога.

★Общее в обоих случаях: гарантия держится на настройке, а настройку можно
потерять — запуском из другого каталога, забытым `COPY` в образ, обновлением
библиотеки, которое заведёт новое умолчание. Настройка выражает намерение;
гарантию даёт то, чего нельзя обойти по устройству. Поэтому здесь мы не
уговариваем Streamlit, а лишаем его возможности: подменяем кэш внешнего адреса
до того, как он кем-либо запрошен, и вызов просто не состоится — ни при печати
баннера, ни в проверке источника веб-сокета, где тот же кэш используется вторым
местом (`streamlit/web/server/server_util.py`).

⚠Это НЕ заменяет запрет исходящего трафика на уровне сети. Опись того, что
уходит наружу и когда, — в README, раздел «Исходящий трафик»; проверка,
которой мы верим, — запуск с запрещённым egress, а не строчка в конфиге.

Запуск:
    python scripts/run_ui.py            # тот же результат, что streamlit run ui/app.py
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

# Корень проекта — родитель каталога scripts/. Опираться на текущий каталог
# нельзя: конфигурация Streamlit ищется относительно него, и запуск из другого
# места молча отменил бы наши настройки — ту самую беду, ради которой заведён
# этот файл.
PROJECT_ROOT = Path(__file__).resolve().parent.parent
APP = PROJECT_ROOT / "ui" / "app.py"


def _silence_external_ip_lookup() -> None:
    """Отменить обращение к checkip.amazonaws.com, не отключая баннер целиком.

    `get_external_ip()` начинается с проверки модульного кэша и возвращает его,
    если он не `None`. Пустая строка — значение не-`None` и при этом ложное,
    поэтому вызывающая сторона считает адрес неопределённым и строку «External
    URL» не печатает, а сетевой запрос не выполняется вовсе.

    Почему именно кэш, а не подмена функции: кэш читают ДВА места — печать
    баннера и список разрешённых источников веб-сокета. Подменять пришлось бы
    оба имени, и любое третье обращение, появившееся в новой версии, прошло бы
    мимо подмены. Кэш — общая для всех точка.

    ⚠Строки «Local URL» и «Network URL» остаются: локальный адрес определяется
    без сетевого обмена (UDP-сокет только спрашивает таблицу маршрутизации,
    пакетов не отправляет), а без них пользователь не узнает, куда идти
    браузером.
    """
    from streamlit import net_util

    net_util._external_ip = ""  # noqa: SLF001


# Префикс переменных окружения Streamlit. Значение задано в самой библиотеке
# (`@click.group(context_settings={"auto_envvar_prefix": "STREAMLIT"})`), и
# менять его нельзя: имена вроде STREAMLIT_SERVER_ADDRESS уже описаны в нашей
# документации и в Dockerfile.
_ENV_PREFIX = "STREAMLIT_"


def _config_options_from_env() -> dict[str, object]:
    """Собрать настройки Streamlit из переменных окружения `STREAMLIT_*`.

    ★Зачем это здесь, хотя переменные «и так работают».

    Они работают НЕ через систему настроек, а через разбор командной строки.
    Штатный `streamlit` — приложение на click, объявленное с
    `auto_envvar_prefix="STREAMLIT"`: click сам подставляет значение переменной
    там, где не передан флаг, и дальше оно живёт как обычный флаг. Файл
    `config.py` читает из окружения только два «чувствительных» значения
    (`server.cookieSecret`, `mapbox.token`) — остальные 340 приезжают
    исключительно из click.

    Наш вход click не поднимает. Без этой функции ВСЕ переменные `STREAMLIT_*`
    перестали бы действовать — молча, без ошибки и без предупреждения. Проверено
    прогоном: с `STREAMLIT_SERVER_ADDRESS=127.0.0.1` сервер всё равно занимал
    `*:8501`. Для нашего образа это прямая поломка: адрес прослушивания там
    задан именно переменной, и в Dockerfile объяснено, почему не флагом.

    Соответствие имён повторяет click: `server.address` → `SERVER_ADDRESS`,
    точка становится подчёркиванием, регистр верхний.

    Разбор значения выполняет сам click (`click.types.convert_type`), а не наш
    самодельный разборщик: тогда «true», «1» и «yes» означают здесь ровно то же,
    что при штатном запуске, и разойтись эти два пути не могут по устройству.

    ⚠Перечень настроек берётся из ШАБЛОНА (`_config_options_template`), а не из
    разобранной конфигурации. Шаблон заполняется при импорте модуля и читать
    файлы не заставляет. Вызов `get_config_options()` здесь означал бы первый
    разбор, а следующий за ним разбор с нашими значениями Streamlit счёл бы
    изменением раздела `[server]` уже работающего сервера и напечатал бы
    предупреждение «please restart streamlit» на ровном месте.
    """
    import click
    from streamlit import config as _config

    from_env: dict[str, object] = {}
    for key, option in _config._config_options_template.items():  # noqa: SLF001
        if option.sensitive:
            # Их Streamlit читает из окружения сам, и намеренно запрещает
            # передавать флагом, чтобы секрет не попал в список процессов.
            continue

        raw = os.environ.get(_ENV_PREFIX + key.replace(".", "_").upper())
        if raw is None:
            continue

        converter = click.types.convert_type(option.type)
        if option.multiple:
            # click разделяет список из переменной окружения тем же символом,
            # что и пути в PATH (двоеточие на этой платформе).
            from_env[key] = tuple(
                converter(part) for part in raw.split(os.path.pathsep) if part
            )
        else:
            from_env[key] = converter(raw)

    return from_env


def main() -> int:
    if not APP.is_file():
        print(f"Не найден интерфейс: {APP}", file=sys.stderr)
        return 1

    # Каталог задаётся явно: от него зависит поиск `.streamlit/config.toml`,
    # каталога `data/` и относительных путей в настройках.
    os.chdir(PROJECT_ROOT)

    _silence_external_ip_lookup()

    from streamlit import config as _config
    from streamlit.web import bootstrap

    # Порядок здесь и есть порядок старшинства, и он повторяет штатный:
    # умолчания библиотеки → `.streamlit/config.toml` → переменные окружения →
    # то, что для продукта не обсуждается.
    flag_options: dict[str, object] = _config_options_from_env()

    # Эти две настройки перекрывают всё, включая окружение, и это осознанно.
    # Обещание «наружу ничего не уходит» не должно отменяться переменной
    # окружения, случайно унаследованной от хоста или от базового образа.
    flag_options.update(
        {
            # Не открывать браузер и не ждать его: сервер поднимается в контейнере.
            "server.headless": True,
            # Сбор статистики выключен третьим, независимым от файла способом.
            "browser.gatherUsageStats": False,
        }
    )

    _config._main_script_path = str(APP)  # noqa: SLF001
    bootstrap.load_config_options(flag_options=flag_options)

    # ★`check_credentials()` штатного запуска здесь НЕ вызывается сознательно.
    # Именно она печатает «Collecting usage statistics…» и приглашение оставить
    # почтовый адрес. Приглашение обращено к разработчику, который поставил
    # библиотеку, а не к пользователю нашего продукта, и в интерфейсе заказчика
    # ему делать нечего. Значение `gatherUsageStats` задано выше явно, так что
    # умолчание, о котором эта функция предупреждает, к нам не применяется.

    bootstrap.run(str(APP), False, sys.argv[1:], flag_options)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
