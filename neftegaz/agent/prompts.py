"""The agent's role and the instructions that govern how it answers.

Requirement 2.1 asks for a defined role, a stated style, and explicit behaviour
when data is missing. The last of those is the one that actually matters: an
analyst that invents a number is worse than one that says it does not know, and
in a regulated industry that difference is the whole product.
"""

