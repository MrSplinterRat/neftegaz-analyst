"""Чтение сценария изменения предложения из вопроса пользователя.

★Это единственное место продукта, где ЧИСЛО, определяющее ответ, добывается из
свободного текста. Всё остальное — цены, запасы, добыча — приходит из файлов и
рядов, где значение либо есть, либо его нет. Здесь же между вопросом и расчётом
стоит разбор, и его отказ не виден никому: прежняя версия возвращала ``0.0`` и
на «сократит на 5%», и на «что с ценой Brent» — то есть **молчание о непонятом
было неотличимо от честного отсутствия сценария**.

Замер, из-за которого модуль и появился (30.08.2026, семь реалистичных
формулировок против прежнего разбора):

    +0.00   если ОПЕК+ сократит добычу на 5%
    +0.00   при сокращении добычи на 500 тыс. барр/сут
    +0.00   если добыча упадёт на 1,5 миллиона баррелей в сутки
    -2.00   не сократит, а увеличит на 2 млн барр/сут      ← знак перевёрнут
    -3.00   сокращение с 2 до 3 млн барр/сут               ← вилка, взят один конец
    +0.00   если добыча вырастет на 2 mb/d
    +0.00   при выпадении 2 млн б/с

Пять из семи — молчаливый ноль: базовый прогноз уезжает как ответ на сценарный
вопрос, и снаружи он выглядит обычным расчётом. Ещё два хуже: они дают ЧИСЛО, и
неверное.

★Поэтому договор модуля другой: у ответа три исхода, а не один.

* **сценария нет** — в вопросе про него ничего, базовый прогноз честен;
* **сценарий прочитан** — есть величина в млн барр./сут;
* **сценарий назван, но не прочитан** — и это ОТДЕЛЬНОЕ состояние, о котором
  обязан узнать и пользователь, и (позже) ветка уточняющего вопроса.

Третий исход и есть весь смысл: он превращает беззвучную ошибку в разговор.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

from neftegaz.config import settings

__all__ = [
    "SupplyScenario",
    "read_supply_scenario",
]


# ── величина ───────────────────────────────────────────────────────────────
#
# Число с необязательными разрядными пробелами и запятой как разделителем
# дробной части: «1,5», «500», «1 200». Неразрывный пробел встречается в
# тексте, вставленном из документов, и его пропуск стоил бы того же
# молчаливого нуля.
_NUM = r"(\d+(?:[  ]\d{3})*(?:[.,]\d+)?)"

# Баррели: и русское «барр./баррелей», и запись «б/с».
_BBL = r"(?:барр\w*|баррел\w*|б\s*/\s*с)"

# ★Единицы перечислены ОТ УЗКОГО К ШИРОКОМУ, и порядок несущий: «2 млн барр»
# обязано разобраться как миллионы, а не как «2 барреля» с мусором вокруг.
# Множитель приводит величину к млн барр./сут — той единице, в которой считает
# `apply_supply_scenario`.
#
# Доля процента считается от мирового предложения, потому что расчёт всё равно
# делит величину на него (`share = supply_change_mb_d / global_supply_mb_d`).
# Пересчёт здесь, а не там, оставляет расчётной части один вход вместо двух.
_UNITS: tuple[tuple[str, float, str], ...] = (
    (rf"{_NUM}\s*(?:%|процент\w*)", settings.global_supply_mb_d / 100.0, "процент"),
    (rf"{_NUM}\s*(?:млн|миллион\w*)\s*\.?\s*{_BBL}", 1.0, "млн барр./сут"),
    (rf"{_NUM}\s*(?:тыс\w*|тысяч\w*)\s*\.?\s*{_BBL}", 0.001, "тыс. барр./сут"),
    (rf"{_NUM}\s*(?:mmb|mb)\s*/?\s*d\b", 1.0, "mb/d"),
    (rf"{_NUM}\s*(?:kb)\s*/?\s*d\b", 0.001, "kb/d"),
    (rf"{_NUM}\s*{_BBL}\s*(?:в\s*сутки|/\s*сут\w*|в\s*день)", 1e-6, "барр./сут"),
)

# ── направление ────────────────────────────────────────────────────────────
#
# ★Корни, а не слова: «сокращение» и «сократит» — разные корни («сокращ» и
# «сократ»), и пропуск второго уже стоил конкретного дефекта. На вопросе «а если
# ОПЕК+ СОКРАТИТ добычу на 2 млн барр./сут?» расчёт посчитал сценарий
# УВЕЛИЧЕНИЯ и выдал падение цены вместо роста — ответ, противоположный вопросу.
#
# ★Ошибка знака дороже ошибки величины: «на сколько» читатель перепроверит,
# направление примет на веру. Корни берутся полные, различающие формы: «пад»
# вошло бы в слово «западный».
_CUT_ROOTS = (
    "сокращ",
    "сократ",
    "снижен",
    "сниз",
    "уменьш",
    "срез",
    "урез",
    "упад",
    "паден",
    "выпаден",
    "потер",
    "выбыт",
    "останов",
    "сверн",
    "cut",
    "reduc",
    "declin",
    "drop",
)
_RAISE_ROOTS = (
    "вырас",
    "выраст",
    "увелич",
    "нараст",
    "наращ",
    "прибав",
    "повыс",
    "рост",
    "подним",
    "добав",
    "rise",
    "increas",
    "grow",
    "boost",
    "raise",
)

_CUT_RE = re.compile("|".join(_CUT_ROOTS))
_RAISE_RE = re.compile("|".join(_RAISE_ROOTS))

# Отрицание непосредственно перед указателем направления переворачивает его:
# «не сократит, а увеличит» — про рост, хотя корень «сократ» в тексте стои́т.
_NEGATION = re.compile(r"\bне\s*$")

# Вилка: «с 2 до 3 млн барр./сут». Один конец брать нельзя — какой именно,
# из текста не следует, а разбор обязан не выбирать за человека.
_RANGE = re.compile(rf"\bс\s*{_NUM}\s*(?:до|по)\s+{_NUM}")

# ★ЦИФРА ГОРИЗОНТА — НЕ ВЕЛИЧИНА СЦЕНАРИЯ.
#
# Ниже по модулю «величина названа» отличается от «величины нет» наличием цифры
# в вопросе. Но в вопросе про прогноз цифра есть почти всегда, и почти всегда
# это ГОРИЗОНТ: «спрогнозируй Brent на 3 месяца, если ОПЕК+ сократит добычу».
# Величины сценария человек тут не называл, а агент отвечал ему «величина
# названа, но единица измерения не опознана» — и тот шёл искать у себя величину,
# которой нет.
#
# ★Переспрос с НЕВЕРНОЙ причиной хуже переспроса без причины: маршрут при этом
# верен, ответ вежлив, и счётчик маршрутов такого не видит вовсе. Замер на
# восьми формулировках: 3 из 8 причин назывались неверно, и все три — там, где
# горизонт записан цифрой.
#
# ★Словарь единиц времени намеренно СВОЙ, а не общий с `requested_horizon_days`:
# там он несёт множители и живёт в другом слое. Расхождение двух словарей ловит
# тест, который гонит одни и те же формулировки через оба разбора.
_HORIZON = re.compile(
    r"\d+(?:[.,]\d+)?\s*"
    r"(?:кв\b|квартал\w*|мес\w*|month\w*|год\w*|лет\b|year\w*|недел\w*|week\w*"
    r"|дн\w*|день|day\w*)"
)

# О чём идёт речь. Указатель направления сам по себе ничего не значит: «упадёт»
# в вопросе про ЦЕНУ — не сценарий предложения, и принимать его за сценарий
# значило бы спрашивать человека там, где спрашивать не о чем.
_SUPPLY = re.compile(
    r"добыч|предложен|производств|поставк|квот|опек|opec|supply|production|output|"
    r"баррел|барр\b|б\s*/\s*с|mb\s*/?\s*d"
)


@dataclass(frozen=True)
class SupplyScenario:
    """Что удалось прочитать про изменение предложения.

    ``value_mb_d`` — изменение в млн барр./сут; отрицательное значит сокращение.
    Читать его в одиночку НЕЛЬЗЯ: ноль тут значит и «сценария нет», и «сценарий
    есть, но не прочитан», а это разные вещи. Различает их ``understood``.
    """

    value_mb_d: float
    stated: bool
    understood: bool
    unit: str = ""
    note: str = ""

    @property
    def unreadable(self) -> bool:
        """Сценарий назван, но не прочитан — единственный случай, требующий слов."""
        return self.stated and not self.understood


def _direction(text: str, at: int) -> int | None:
    """Знак изменения по указателю направления, ближайшему к числу.

    Возвращает −1 (сокращение), +1 (рост) или ``None``, если направление в
    вопросе не названо вовсе. ★Именно ``None``, а не «по умолчанию рост»:
    молчаливое умолчание здесь и есть тот дефект, ради которого модуль писан.

    Ближайший, а не первый: во фразе «не сократит, а увеличит на 2 млн барр./сут»
    оба указателя стоя́т слева от числа, и верен из них последний.
    """
    best: tuple[int, int] | None = None  # (расстояние, знак)
    for pattern, sign in ((_CUT_RE, -1), (_RAISE_RE, +1)):
        for found in pattern.finditer(text):
            actual = -sign if _NEGATION.search(text[: found.start()]) else sign
            distance = abs(found.start() - at)
            if best is None or distance < best[0]:
                best = (distance, actual)
    return None if best is None else best[1]


def read_supply_scenario(question: str) -> SupplyScenario:
    """Прочитать сценарий предложения из вопроса.

    Ни один исход не выражается исключением: вопрос пользователя — не ошибка
    программы, а вход, который бывает непонятным. Непонятность возвращается
    значением и едет дальше как факт.
    """
    text = question.lower()

    matches = [
        (found, factor, unit)
        for pattern, factor, unit in _UNITS
        for found in [re.search(pattern, text)]
        if found is not None
    ]

    if not matches:
        # ★Указателя направления МАЛО, чтобы объявить сценарий: «упадёт» есть и в
        # вопросе «спрогнозируй Brent, цена упадёт?», где речь о ЦЕНЕ, а не о
        # предложении. Без этой оговорки уточняющий вопрос задавался бы там, где
        # спрашивать не о чем, — а переспрашивающий впустую агент хуже молчащего.
        has_cue = _CUT_RE.search(text) is not None or _RAISE_RE.search(text) is not None
        if not (has_cue and _SUPPLY.search(text)):
            return SupplyScenario(0.0, stated=False, understood=True)
        # Число названо рядом с указателем направления, но единица не опознана:
        # «сократит добычу на 2» — величина есть, а чего именно два, неизвестно.
        # ★Цифры горизонта из счёта вычеркнуты: «на 3 месяца» — про срок, а не
        # про добычу, и называть её величиной сценария значит соврать о том,
        # что именно осталось непонятым (см. `_HORIZON` выше).
        if re.search(r"\d", _HORIZON.sub(" ", text)):
            return SupplyScenario(
                0.0,
                stated=True,
                understood=False,
                note="величина названа, но единица измерения не опознана",
            )
        # ★Сценарий без величины вовсе — «а если ОПЕК+ сократит добычу?». Раньше
        # это молча давало базовый прогноз, то есть ответ на другой вопрос.
        return SupplyScenario(
            0.0,
            stated=True,
            understood=False,
            note="сказано про изменение добычи, но не названа величина",
        )

    if _RANGE.search(text):
        return SupplyScenario(
            0.0,
            stated=True,
            understood=False,
            note="названа вилка значений, а не одна величина",
        )

    # Из нескольких опознанных единиц берётся самая узкая — она стои́т первой
    # в `_UNITS`. Разные единицы в одном вопросе («на 5% или на 2 млн барр.»)
    # это тоже вилка, только записанная иначе.
    if len({unit for _, _, unit in matches}) > 1:
        return SupplyScenario(
            0.0,
            stated=True,
            understood=False,
            note="величина названа в двух разных единицах сразу",
        )

    found, factor, unit = matches[0]
    magnitude = float(found.group(1).replace(" ", "").replace(" ", "").replace(",", "."))
    sign = _direction(text, found.start())
    if sign is None:
        return SupplyScenario(
            0.0,
            stated=True,
            understood=False,
            unit=unit,
            note="не сказано, рост это или сокращение",
        )
    return SupplyScenario(sign * magnitude * factor, stated=True, understood=True, unit=unit)
